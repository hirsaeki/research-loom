#!/usr/bin/env python3
"""Generate docs/test-map.md: which test modules import each production module (#507).

A test module "covers" a production module when it imports it directly
(``import a.b``, ``from a.b import name`` or ``from a import b``). Indirect use,
for example through ``LocalApplicationFacade``, is not listed; the coverage
report shows that. Run with ``--check`` to fail when the committed map is stale.
"""

from __future__ import annotations

import argparse
import ast
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "docs" / "test-map.md"
PRODUCTION_TREES = ("core", "plugins")
TEST_TREES = ("tests/unit", "tests/runtime", "tests/contracts")


def module_name(path: Path) -> str:
    parts = path.relative_to(ROOT).with_suffix("").parts
    return ".".join(parts[:-1] if parts[-1] == "__init__" else parts)


def production_modules() -> dict[str, Path]:
    return {
        module_name(path): path
        for tree in PRODUCTION_TREES
        for path in sorted((ROOT / tree).rglob("*.py"))
        if path.name != "__init__.py" and "__pycache__" not in path.parts
    }


def imported_modules(path: Path, known: dict[str, Path]) -> set[str]:
    found: set[str] = set()
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"), filename=str(path))):
        if isinstance(node, ast.Import):
            found.update(alias.name for alias in node.names if alias.name in known)
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            if node.module in known:
                found.add(node.module)
            for alias in node.names:
                if f"{node.module}.{alias.name}" in known:
                    found.add(f"{node.module}.{alias.name}")
    return found


def render() -> str:
    known = production_modules()
    tests_by_module: dict[str, list[str]] = defaultdict(list)
    for tree in TEST_TREES:
        for path in sorted((ROOT / tree).rglob("test_*.py")):
            for module in imported_modules(path, known):
                tests_by_module[module].append(path.relative_to(ROOT).as_posix())
    lines = [
        "# Test map",
        "",
        "Generated by `scripts/test_map.py`; do not edit by hand. Regenerate with",
        "`uv run --frozen python scripts/test_map.py`. A test is listed when it imports the",
        "module directly; modules reached only through the Application Facade show `—`.",
        "Unit tests live in `tests/unit/<package>/`, integration and acceptance tests in",
        "`tests/runtime/`, and contract tests in `tests/contracts/` (#507).",
        "",
        "| Module | Tests that import it |",
        "| --- | --- |",
    ]
    for module in sorted(known):
        tests = sorted(set(tests_by_module.get(module, [])))
        cell = "<br>".join(f"`{test}`" for test in tests) if tests else "—"
        lines.append(f"| `{known[module].relative_to(ROOT).as_posix()}` | {cell} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if docs/test-map.md is stale")
    args = parser.parse_args(argv)
    fresh = render()
    if args.check:
        current = MAP.read_bytes().decode("utf-8").replace("\r\n", "\n") if MAP.is_file() else ""
        if current != fresh:
            print("docs/test-map.md is stale; run: uv run --frozen python scripts/test_map.py")
            return 1
        print("docs/test-map.md is current")
        return 0
    MAP.write_text(fresh, encoding="utf-8", newline="\n")
    print("wrote docs/test-map.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
